-- Allocate one prepaid credit atomically whenever the package-only service is
-- attached to an appointment. This is the fail-closed entitlement boundary.
CREATE OR REPLACE FUNCTION shiloh_allocate_package_session()
RETURNS TRIGGER AS $$
DECLARE
  v_client_id BIGINT;
  v_starts_at TIMESTAMPTZ;
  v_package_id BIGINT;
  v_entitlement_id BIGINT;
  v_sessions_total INTEGER;
  v_used INTEGER;
BEGIN
  SELECT sp.id INTO v_package_id
    FROM service_packages sp
   WHERE sp.session_service_id = NEW.service_id
     AND sp.status = 'active'
   LIMIT 1;

  IF v_package_id IS NULL THEN
    RETURN NEW;
  END IF;

  SELECT a.client_id, a.starts_at INTO v_client_id, v_starts_at
    FROM appointments a
   WHERE a.id = NEW.appointment_id
   FOR UPDATE;

  SELECT e.id, e.sessions_total INTO v_entitlement_id, v_sessions_total
    FROM client_package_entitlements e
   WHERE e.client_id = v_client_id
     AND e.package_id = v_package_id
     AND e.status = 'active'
     AND e.payment_status = 'paid'
     AND NOW() >= e.starts_at
     AND NOW() < e.expires_at
     AND v_starts_at >= e.starts_at
     AND v_starts_at < e.expires_at
   ORDER BY e.expires_at, e.id
   FOR UPDATE
   LIMIT 1;

  IF v_entitlement_id IS NULL THEN
    RAISE EXCEPTION 'PACKAGE_ENTITLEMENT_REQUIRED' USING ERRCODE = 'P0001';
  END IF;

  SELECT COUNT(*)::INTEGER INTO v_used
    FROM package_session_redemptions r
   WHERE r.entitlement_id = v_entitlement_id
     AND r.status IN ('reserved','redeemed');

  IF v_used >= v_sessions_total THEN
    RAISE EXCEPTION 'PACKAGE_CREDITS_EXHAUSTED' USING ERRCODE = 'P0001';
  END IF;

  NEW.price_snapshot := 0;
  INSERT INTO package_session_redemptions (entitlement_id, appointment_id, status)
  VALUES (v_entitlement_id, NEW.appointment_id, 'reserved');

  UPDATE appointments
     SET total_price = 0,
         notes = CONCAT_WS(E'\n', NULLIF(notes, ''), 'Prepaid Sports Massage monthly package session'),
         updated_at = NOW()
   WHERE id = NEW.appointment_id;

  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trg_allocate_package_session ON appointment_services;
CREATE TRIGGER trg_allocate_package_session
BEFORE INSERT ON appointment_services
FOR EACH ROW EXECUTE FUNCTION shiloh_allocate_package_session();

-- Completed appointments consume a credit. Cancelled/no-show appointments release
-- it; the 24-hour cancellation notice is communicated to clients but no automatic
-- punitive forfeiture is invented without an explicit clinic rule.
CREATE OR REPLACE FUNCTION shiloh_sync_package_redemption_status()
RETURNS TRIGGER AS $$
BEGIN
  IF NEW.status = OLD.status THEN
    RETURN NEW;
  END IF;

  IF NEW.status = 'completed' THEN
    UPDATE package_session_redemptions
       SET status = 'redeemed', redeemed_at = NOW(), released_at = NULL, updated_at = NOW()
     WHERE appointment_id = NEW.id AND status = 'reserved';
  ELSIF NEW.status IN ('cancelled','no_show') THEN
    UPDATE package_session_redemptions
       SET status = 'released', released_at = NOW(), updated_at = NOW()
     WHERE appointment_id = NEW.id AND status = 'reserved';
  END IF;

  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trg_sync_package_redemption_status ON appointments;
CREATE TRIGGER trg_sync_package_redemption_status
AFTER UPDATE OF status ON appointments
FOR EACH ROW EXECUTE FUNCTION shiloh_sync_package_redemption_status();
