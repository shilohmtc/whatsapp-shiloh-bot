-- Durable prepaid massage-package capability.
-- Sports Massage — Monthly Package: R1,400, four 50-minute sessions, valid for 30 days.
-- Package sessions are not ordinary direct-booking catalogue products.

CREATE TABLE IF NOT EXISTS service_packages (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  slug TEXT NOT NULL UNIQUE,
  name TEXT NOT NULL,
  family_name TEXT NOT NULL DEFAULT 'Massage Packages',
  session_service_id BIGINT NOT NULL REFERENCES services(id) ON DELETE RESTRICT,
  package_price NUMERIC(12,2) NOT NULL,
  sessions_included INTEGER NOT NULL,
  validity_days INTEGER NOT NULL,
  cancellation_notice_hours INTEGER NOT NULL DEFAULT 24,
  customer_description TEXT,
  status TEXT NOT NULL DEFAULT 'active',
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT service_packages_price_check CHECK (package_price >= 0),
  CONSTRAINT service_packages_sessions_check CHECK (sessions_included > 0),
  CONSTRAINT service_packages_validity_check CHECK (validity_days > 0),
  CONSTRAINT service_packages_status_check CHECK (status IN ('active','inactive'))
);

CREATE TABLE IF NOT EXISTS client_package_entitlements (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  client_id BIGINT NOT NULL REFERENCES clients(id) ON DELETE CASCADE,
  package_id BIGINT NOT NULL REFERENCES service_packages(id) ON DELETE RESTRICT,
  payment_status TEXT NOT NULL DEFAULT 'paid',
  purchase_price NUMERIC(12,2) NOT NULL,
  purchased_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  starts_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  expires_at TIMESTAMPTZ NOT NULL,
  sessions_total INTEGER NOT NULL,
  status TEXT NOT NULL DEFAULT 'active',
  activated_by_admin_id BIGINT REFERENCES staff_admin_accounts(id) ON DELETE SET NULL,
  notes TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT client_package_entitlements_payment_check CHECK (payment_status IN ('paid','refunded','void')),
  CONSTRAINT client_package_entitlements_status_check CHECK (status IN ('active','cancelled','exhausted')),
  CONSTRAINT client_package_entitlements_sessions_check CHECK (sessions_total > 0),
  CONSTRAINT client_package_entitlements_window_check CHECK (expires_at > starts_at)
);

CREATE INDEX IF NOT EXISTS idx_client_package_entitlements_client
  ON client_package_entitlements(client_id, status, expires_at);

CREATE TABLE IF NOT EXISTS package_session_redemptions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  entitlement_id BIGINT NOT NULL REFERENCES client_package_entitlements(id) ON DELETE CASCADE,
  appointment_id BIGINT NOT NULL REFERENCES appointments(id) ON DELETE CASCADE,
  status TEXT NOT NULL DEFAULT 'reserved',
  reserved_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  redeemed_at TIMESTAMPTZ,
  released_at TIMESTAMPTZ,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT package_session_redemptions_status_check CHECK (status IN ('reserved','redeemed','released')),
  CONSTRAINT package_session_redemptions_appointment_unique UNIQUE (appointment_id)
);

CREATE INDEX IF NOT EXISTS idx_package_session_redemptions_entitlement
  ON package_session_redemptions(entitlement_id, status);

CREATE TABLE IF NOT EXISTS package_enquiries (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  client_id BIGINT REFERENCES clients(id) ON DELETE SET NULL,
  package_id BIGINT NOT NULL REFERENCES service_packages(id) ON DELETE RESTRICT,
  normalized_whatsapp TEXT,
  status TEXT NOT NULL DEFAULT 'open',
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT package_enquiries_status_check CHECK (status IN ('open','contacted','converted','closed'))
);

